"""Proposal schema: the structured changes the agent proposes, its final reply, and the one routine that applies a change."""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from datetime import date

from pawpal_system import Scheduler, Task


@dataclass(frozen=True)
class MoveChange:
    """Move an existing pending task to a new time (and optionally a new date)."""

    task_id: str
    new_time: str
    new_date: date | None
    rationale: str


@dataclass(frozen=True)
class AddChange:
    """Add a new non-medication task to a pet; task_id is generated by the tool, not the model."""

    task_id: str
    pet_name: str
    description: str
    time: str
    duration_minutes: int
    due_date: date
    rationale: str
    priority: str = "medium"
    frequency: str = "once"
    combinable: bool = False


@dataclass(frozen=True)
class CompleteChange:
    """Mark an existing pending task complete (recurring tasks get their next occurrence)."""

    task_id: str
    rationale: str


Change = MoveChange | AddChange | CompleteChange
CHANGE_TYPES = (MoveChange, AddChange, CompleteChange)

# Allowed keys per kind for parse_change; anything else (e.g. "medication", "dose_text") is rejected.
_REQUIRED = {
    "move": {"task_id", "new_time", "rationale"},
    "add": {"task_id", "pet_name", "description", "time", "duration_minutes", "due_date", "rationale"},
    "complete": {"task_id", "rationale"},
}
_OPTIONAL = {
    "move": {"new_date"},
    "add": {"priority", "frequency", "combinable"},
    "complete": set(),
}
_FIELD_TYPES: dict[str, type] = {
    "task_id": str,
    "new_time": str,
    "new_date": str,  # ISO "YYYY-MM-DD" (or None)
    "rationale": str,
    "pet_name": str,
    "description": str,
    "time": str,
    "duration_minutes": int,
    "due_date": str,  # ISO "YYYY-MM-DD"
    "priority": str,
    "frequency": str,
    "combinable": bool,
}


def change_kind(change: Change) -> str:
    """Return "move", "add", or "complete" for a change."""
    if isinstance(change, MoveChange):
        return "move"
    if isinstance(change, AddChange):
        return "add"
    return "complete"


def change_label(index: int, change: object) -> str:
    """Return a short label like "change 2 (move 1a2b3c4d)" for error messages."""
    if isinstance(change, CHANGE_TYPES):
        return f"change {index} ({change_kind(change)} {change.task_id})"
    return f"change {index} ({type(change).__name__})"


def parse_change(data: dict) -> Change:
    """Build a Change from a dict with a "kind" key; raise ValueError on unknown kinds or unexpected keys."""
    kind = data.get("kind")
    if kind not in _REQUIRED:
        raise ValueError(f"Unsupported change kind {kind!r}: use move, add, or complete")
    keys = set(data) - {"kind"}
    missing = _REQUIRED[kind] - keys
    extra = keys - _REQUIRED[kind] - _OPTIONAL[kind]
    if missing:
        raise ValueError(f"{kind} change is missing {sorted(missing)}")
    if extra:
        raise ValueError(f"{kind} change has unexpected fields {sorted(extra)}")
    values = {k: v for k, v in data.items() if k != "kind"}
    for key, value in values.items():
        expected = _FIELD_TYPES[key]
        if key == "new_date" and value is None:
            continue
        if not isinstance(value, expected) or (expected is int and isinstance(value, bool)):
            raise ValueError(f"{key} must be of type {expected.__name__}, got {value!r}")
    if not values["rationale"].strip():
        raise ValueError("rationale must not be empty")
    if kind == "move":
        new_date = values.get("new_date")
        values["new_date"] = date.fromisoformat(new_date) if new_date else None
        return MoveChange(**values)
    if kind == "add":
        values["due_date"] = date.fromisoformat(values["due_date"])
        return AddChange(**values)
    return CompleteChange(**values)


@dataclass(frozen=True)
class FinalReply:
    """The model's closing JSON message."""

    summary: str
    confidence: float
    notes: list[str]
    refusal: str | None


FINAL_REPLY_KEYS = {"summary", "confidence", "notes", "refusal"}


def parse_final_reply(text: str, change_count: int) -> FinalReply:
    """Parse the model's strict-JSON final reply; raise ValueError if it is malformed."""
    try:
        data = json.loads(text)
    except json.JSONDecodeError as err:
        raise ValueError(f"Final reply is not valid JSON ({err.msg}); reply with only the JSON object") from err
    if not isinstance(data, dict):
        raise ValueError("Final reply must be a JSON object")
    if set(data) != FINAL_REPLY_KEYS:
        raise ValueError(f"Final reply must have exactly the keys {sorted(FINAL_REPLY_KEYS)}")
    summary, confidence, notes, refusal = (data[k] for k in ("summary", "confidence", "notes", "refusal"))
    if not isinstance(summary, str):
        raise ValueError("summary must be a string")
    if isinstance(confidence, bool) or not isinstance(confidence, (int, float)):
        raise ValueError("confidence must be a number between 0 and 1")
    if not 0 <= confidence <= 1:
        raise ValueError(f"confidence must be between 0 and 1, got {confidence}")
    if not isinstance(notes, list) or not all(isinstance(n, str) for n in notes):
        raise ValueError("notes must be a list of strings")
    if refusal is not None and not isinstance(refusal, str):
        raise ValueError("refusal must be a string or null")
    if refusal and change_count:
        raise ValueError("A refusal cannot also propose changes")
    return FinalReply(summary, float(confidence), list(notes), refusal or None)


@dataclass
class Proposal:
    """What the agent hands to the human: changes, rationale, confidence, and verification result."""

    request: str
    day: date
    changes: list[Change] = field(default_factory=list)
    summary: str = ""
    model_confidence: float = 0.0  # what the model said (0-1)
    confidence: float = 0.0  # after score_confidence()
    notes: list[str] = field(default_factory=list)
    refusal: str | None = None
    verified: bool = False
    errors: list[str] = field(default_factory=list)
    retries: int = 0


def apply_change(scheduler: Scheduler, change: Change, today: date) -> str:
    """Apply one change to the scheduler's owner and return a one-line description; raise ValueError if invalid."""
    owner = scheduler.owner
    if isinstance(change, MoveChange):
        task = scheduler.move_task(change.task_id, change.new_time, change.new_date)
        return f"Moved {task.description} ({task.pet_name}) to {task.due_date.isoformat()} {task.time}"
    if isinstance(change, AddChange):
        pet = owner.get_pet(change.pet_name)
        if pet is None:
            raise ValueError(f"Unknown pet {change.pet_name!r}")
        if owner.find_task(change.task_id) is not None:
            raise ValueError(f"Task id {change.task_id!r} already exists")
        task = Task(
            change.description,
            change.time,
            change.duration_minutes,
            change.priority,
            change.frequency,
            due_date=change.due_date,
            task_id=change.task_id,
            combinable=change.combinable,
        )
        pet.add_task(task)
        return f"Added {task.description} ({pet.name}) on {task.due_date.isoformat()} at {task.time}"
    if isinstance(change, CompleteChange):
        found = owner.find_task(change.task_id)
        if found is None:
            raise ValueError(f"Unknown task id {change.task_id!r}")
        task = found[1]
        if task.completed:
            raise ValueError(f"Task {task.description!r} is already completed")
        next_task = scheduler.mark_task_complete(change.task_id, today)
        line = f"Completed {task.description} ({task.pet_name})"
        if next_task is not None:
            line += f"; next one due {next_task.due_date.isoformat()}"
        return line
    raise ValueError(f"Unsupported change type {type(change).__name__}")
